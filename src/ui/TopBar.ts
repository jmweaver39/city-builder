/** Traffic stats, sim speed, the global traffic slider, the clock, undo and redo. */
import type { UiContext } from './context';
import { el, iconButton } from './dom';
import { ICONS } from './icons';

function statBox(label: string): { root: HTMLElement; value: HTMLElement } {
  const value = el('b', { text: '0' });
  return { root: el('div', { class: 'stat' }, value, el('span', { text: label })), value };
}

function clockText(hours: number): string {
  const h = Math.floor(hours) % 24;
  const m = Math.floor((hours - Math.floor(hours)) * 60);
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
}

export class TopBar {
  readonly root: HTMLElement;
  private readonly active = statBox('Vehicles');
  private readonly flow = statBox('Flow');
  private readonly throughput = statBox('Per hour');
  private readonly jammed = statBox('Jammed');
  private readonly mean = statBox('Mean km/h');
  private readonly name = el('div', { class: 'project-name' });
  private readonly speedButtons: { speed: number; btn: HTMLButtonElement }[] = [];
  private readonly undoBtn: HTMLButtonElement;
  private readonly redoBtn: HTMLButtonElement;
  private readonly trafficInput: HTMLInputElement;
  private readonly trafficOut = el('output', { text: '100%' });
  private readonly timeInput: HTMLInputElement;
  private readonly timeOut = el('output', { text: '12:00' });
  private lastSpeed = 1;

  constructor(private readonly ui: UiContext, openMenu: () => void) {
    const { net, renderer, history } = ui;

    const speeds = el('div', { class: 'speed-group' });
    const addSpeed = (speed: number, label: string, tip: string, key?: string) => {
      const btn = iconButton(label, { tip, keyHint: key, onClick: () => this.setSpeed(speed) });
      this.speedButtons.push({ speed, btn });
      speeds.append(btn);
    };
    addSpeed(0, ICONS.pause, 'Pause', 'Space');
    addSpeed(1, '1x', 'Normal speed', '1');
    addSpeed(2, '2x', 'Double speed', '2');
    addSpeed(4, '4x', 'Four times speed', '3');

    this.trafficInput = el('input', {
      attrs: { type: 'range', min: '0', max: '4', step: '0.05', 'aria-label': 'Global traffic' },
      on: {
        input: () => {
          history.hint('Change traffic level', 'traffic');
          net.setTraffic({ multiplier: this.trafficInput.valueAsNumber });
        },
        change: () => this.trafficInput.blur(),
      },
    });
    this.timeInput = el('input', {
      attrs: { type: 'range', min: '0', max: '24', step: '0.25', 'aria-label': 'Time of day' },
      on: {
        input: () => {
          renderer.setTimeOfDay(this.timeInput.valueAsNumber);
          this.timeOut.textContent = clockText(this.timeInput.valueAsNumber);
        },
        change: () => this.timeInput.blur(),
      },
    });

    this.undoBtn = iconButton(ICONS.undo, { tip: 'Undo', keyHint: 'Ctrl+Z', onClick: () => history.undo() });
    this.redoBtn = iconButton(ICONS.redo, { tip: 'Redo', keyHint: 'Ctrl+Shift+Z', onClick: () => history.redo() });

    this.root = el(
      'div',
      { class: 'panel topbar' },
      iconButton(ICONS.menu, { tip: 'Menu', keyHint: 'Esc', onClick: openMenu }),
      this.name,
      el('div', { class: 'top-sep' }),
      el('div', { class: 'stats', tip: 'Live traffic. Click for the graph', on: { click: () => ui.openStats() } }, this.active.root, this.flow.root, this.throughput.root, this.jammed.root, this.mean.root),
      iconButton(ICONS.chart, { tip: 'Traffic statistics', onClick: () => ui.openStats() }),
      el('div', { class: 'grow' }),
      el('div', { class: 'slider-box', tip: 'Traffic generated by every endpoint, 0 to 400%' }, el('label', { text: 'Traffic' }), this.trafficInput, this.trafficOut),
      el('div', { class: 'top-sep' }),
      speeds,
      el('div', { class: 'top-sep' }),
      el('div', { class: 'slider-box', tip: 'Time of day' }, el('label', { text: 'Time' }), this.timeInput, this.timeOut),
      el('div', { class: 'top-sep' }),
      this.undoBtn,
      this.redoBtn,
    );
    ui.host.append(this.root);
    net.onChange(() => this.syncProject());
    history.subscribe(() => this.syncHistory());
    this.syncProject();
    this.syncHistory();
    this.syncSpeed();
    this.syncClock();
  }

  setSpeed(speed: number): void {
    if (speed !== 0) this.lastSpeed = speed;
    this.ui.sim.speed = speed;
    this.syncSpeed();
  }

  togglePause(): void {
    this.setSpeed(this.ui.sim.speed === 0 ? this.lastSpeed : 0);
  }

  syncSpeed(): void {
    for (const { speed, btn } of this.speedButtons) btn.classList.toggle('active', speed === this.ui.sim.speed);
  }

  private syncProject(): void {
    const { net } = this.ui;
    this.name.textContent = net.project.name;
    const m = net.traffic.multiplier;
    if (document.activeElement !== this.trafficInput) this.trafficInput.value = String(m);
    this.trafficOut.textContent = `${Math.round(m * 100)}%`;
  }

  private syncHistory(): void {
    const { history } = this.ui;
    this.undoBtn.disabled = !history.canUndo;
    this.redoBtn.disabled = !history.canRedo;
    this.undoBtn.dataset.tip = history.undoLabel ? `Undo ${history.undoLabel}` : 'Undo';
    this.redoBtn.dataset.tip = history.redoLabel ? `Redo ${history.redoLabel}` : 'Redo';
  }

  private syncClock(): void {
    const hours = this.ui.renderer.getTimeOfDay();
    this.timeInput.value = String(hours);
    this.timeOut.textContent = clockText(hours);
  }

  /** Called a few times a second. */
  tick(): void {
    const s = this.ui.sim.stats();
    this.active.value.textContent = s.active.toLocaleString();
    this.flow.value.textContent = `${Math.round(s.flow * 100)}%`;
    this.throughput.value.textContent = Math.round(s.throughputPerHour).toLocaleString();
    this.jammed.value.textContent = s.jammed.toLocaleString();
    this.mean.value.textContent = Math.round(s.meanSpeedKmh).toString();
  }
}
